// src/hooks.ts
import { writeFileSync, mkdirSync, chmodSync } from 'node:fs';
import { join } from 'node:path';
import { runGit } from './git.js';

export function installGitHooks(repoRoot: string): void {
  const hooksDir = join(repoRoot, '.githooks');
  mkdirSync(hooksDir, { recursive: true });

  const preCommitSh = join(hooksDir, 'pre-commit');
  const preCommitPs1 = join(hooksDir, 'pre-commit.ps1');

  // PowerShell hook script
  const ps1Content = `# Generated by branch-agent-worker
$worktreeRoot = git rev-parse --show-toplevel 2>$null
if (-not $worktreeRoot) { exit 0 }

$worktreeName = Split-Path $worktreeRoot -Leaf
$statusFile = Join-Path $worktreeRoot ".agent-status.json"

# Check 1: Must be explicitly claimed via branch-agent-worker
if (-not (Test-Path $statusFile)) {
    Write-Error "COMMIT BLOCKED: Worktree '$worktreeName' has not been acquired via branch-agent-worker (.agent-status.json missing). Run 'baw claim' first."
    exit 1
}

# Check 2: Verify not behind upstream
git fetch origin --quiet 2>$null
$behind = (git rev-list --count HEAD..@{u} 2>$null)
if ($behind -and [int]$behind.Trim() -gt 0) {
    Write-Error "COMMIT BLOCKED: Worktree '$worktreeName' is $behind commits behind upstream. Run 'git merge --ff-only' before committing."
    exit 1
}

exit 0
`;

  // Shell script wrapper
  const shContent = `#!/bin/sh
# Generated by branch-agent-worker
hook_dir="$(cd "$(dirname "$0")" && pwd -W 2>/dev/null || pwd)"

if command -v pwsh >/dev/null 2>&1; then
    PS_BIN="pwsh"
elif command -v powershell >/dev/null 2>&1; then
    PS_BIN="powershell"
else
    # Fallback POSIX check if PowerShell is not available
    status_file="$(git rev-parse --show-toplevel 2>/dev/null)/.agent-status.json"
    if [ ! -f "$status_file" ]; then
        echo "COMMIT BLOCKED: Worktree has not been claimed via branch-agent-worker (.agent-status.json missing)." >&2
        exit 1
    fi
    exit 0
fi

"$PS_BIN" -NoProfile -ExecutionPolicy Bypass -File "$hook_dir/pre-commit.ps1" "$@"
exit $?
`;

  writeFileSync(preCommitPs1, ps1Content, 'utf-8');
  writeFileSync(preCommitSh, shContent, 'utf-8');

  try {
    chmodSync(preCommitSh, 0o755);
  } catch {
    // Windows permissions
  }

  // Set core.hooksPath
  runGit(`config core.hooksPath "${hooksDir.replace(/\\/g, '/')}"`, repoRoot);
}
